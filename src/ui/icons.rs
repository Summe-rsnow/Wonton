/// Renders an inline SVG vector icon whose stroke/fill tracks `color`.
pub(crate) fn svg_icon(
    markup: &'static str,
    size: f32,
    color: impl Fn() -> AdaptiveColor + 'static,
) -> impl IntoElement {
    svg(ImageSrc::svg_markup(markup))
        .size(px(size))
        .text_color(color)
}

/// Renders the full-color Wonton brand mark in its authored Gemini gradients.
pub(crate) fn brand_mark(size: f32) -> impl IntoElement {
    svg(ImageSrc::svg_markup(BRAND_MARK)).size(px(size))
}

/// Returns the cached full-color 64x64 data URI for the system tray icon.
pub(crate) fn tray_icon_src() -> ImageSrc {
    static DATA_URI: OnceLock<String> = OnceLock::new();
    let uri = DATA_URI.get_or_init(|| {
        let b64 = base64::engine::general_purpose::STANDARD.encode(TRAY_ICON_PNG);
        format!("data:image/png;base64,{b64}")
    });
    ImageSrc::from(uri.as_str())
}
